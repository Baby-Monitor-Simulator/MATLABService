    %% getDevices helper functions
    methods (Access = private)
        function devices = createHwmgrDevices(obj)
            import ividevapp.IvidevDeviceProvider

            % Creates hardware manager device cards for discovered
            % instruments that can be communicated with using IVI or
            % VXIplug&play drivers.

            devices = matlab.hwmgr.internal.Device.empty;

            try
                % Turn off warning for partially detected Visa resources
                % incase visadevlist is not able to detect all resources
                % within the Timeout specified.
                warnstate = warning;
                cleanupObj = onCleanup(@()warning(warnstate));
                warning("off", "instrument:interface:visa:timeoutExpiredPartialList");

                % Run visadevlist to get VISA resource, model, vendor,
                % serial number information for all discovered devices.
                visaResourceList = visadevlist("Timeout", 100);

                % Trigger onCleanup callback to reinstate original warning
                % state.
                clear cleanupObj
            catch
                % Error with visadevlist indicates VISA installation issue,
                % return early with empty device list.
                % This is needed for hardwareManager launch workflow.
                return
            end

            if isempty(visaResourceList)
                return
            end

            for i = 1:size(visaResourceList, 1)
                if visaResourceList.Model(i) == ""
                    % Not a test and measurement device. Model is needed
                    % for test and measurement devices.
                    continue
                end

                % Populate model and vendor name as device card title.
                vendorStr = visaResourceList.Vendor(i);
                deviceName = visaResourceList.Model(i) + blanks(1) + vendorStr;
                device = matlab.hwmgr.internal.Device(deviceName);

                [iconFieldName, icon] = matlab.hwmgr.internal.data.plugins.InstrumentExplorerDataPlugin.getIconDetails("DeviceCardOrAppletDataIcon", obj.DeviceCard);
                device.(iconFieldName) = icon;

                % Set DeviceEnumerableConfigData to true. This is needed
                % for DetectedDeviceDescriptor
                device.DeviceEnumerableConfigData = matlab.hwmgr.internal.data.DataFactory. ...
                    createDeviceEnumerableConfigData("ividevapp.IvidevApp", ...
                    "ividevapp.DetectedDeviceDescriptor", true);

                % Save the ResourceName to be used by the ividev app to
                % form a connection to the instrument.
                % Also save the Model and SerialNumber to display in the
                % configuration tab page.
                device.CustomData.ResourceName = visaResourceList.ResourceName(i);
                device.CustomData.Model = visaResourceList.Model(i);
                device.CustomData.SerialNumber = visaResourceList.SerialNumber(i);

                % Set the device UUID. This needs to be the same as
                % VisaExplorer if we want to show one combined card for
                % devices detected by both the app.
                device.UUID = compose("%s_%s", visaResourceList.ResourceName(i), visaResourceList.SerialNumber(i));

                % Set the information that will be displayed on the device
                % card below the title.
                deviceCardFirstRowDetails = [message("ividevapp:ividevapp:Resource").string, visaResourceList.ResourceName(i)];
                deviceCardSecondRowDetails = [message("ividevapp:ividevapp:SerialNumber").string, visaResourceList.SerialNumber(i)];

                device.DeviceCardDisplayInfo = [ ...
                    deviceCardFirstRowDetails; ...
                    deviceCardSecondRowDetails ...
                    ];

                device.DeviceAppletData = matlab.hwmgr.internal.data.DataFactory.createDeviceAppletData("ividevapp.IvidevApp", "IC");

                devices(end+1) = device; %#ok<AGROW>
            end
        end
