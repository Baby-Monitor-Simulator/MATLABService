    %% Overridden hardware manager methods
    methods
        function devices = getDevices(obj)
            devices = createHwmgrDevices(obj);
        end

        function descriptor = getDeviceParamDescriptors(obj)
            % If NonEnumDescriptor has not been created, create it.
            if isempty(obj.NonEnumDescriptor)
                createNonEnumDescriptor(obj);
            end

            % Return the non-enum descriptor to Hardware Manager.
            descriptor = obj.NonEnumDescriptor;
        end

        function descriptor = getConfigureParamDescriptors(obj)
            % If DetectedDeviceDescriptor has not been created, create it.
            if isempty(obj.DetectedDeviceDescriptor)
                createDetectedDeviceDescriptor(obj);
            end

            % Return the enum descriptor to Hardware Manager.
            descriptor = obj.DetectedDeviceDescriptor;
        end
    end

