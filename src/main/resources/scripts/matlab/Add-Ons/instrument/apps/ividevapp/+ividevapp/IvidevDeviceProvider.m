            % Creates descriptor for non-enum devices created by the user.

            descriptor = ividevapp.NonEnumDescriptor();

            fieldLabel = @(msgLabel) message("ividevapp:ividevapp:" + msgLabel).getString();
            resourceSectionName = message("ividevapp:ividevapp:Resource").getString();

            % Interface Dropdown
            descriptor.addParameter('Interface', ...
                fieldLabel("Interface"), ...
                "DropDown", ...
                @descriptor.interfaceValuesFcn, ...
                function_handle.empty, ...
                resourceSectionName);

            % Resource Edit field
            descriptor.addParameter('ResourceName', ...
                fieldLabel("Resource"), ...
                "EditField", ...
                @descriptor.generateResourceNameChangeFcn, ...
                function_handle.empty, ...
                resourceSectionName);

            % Generate Resource Button
            [~, icon] = matlab.hwmgr.internal.data.plugins.InstrumentExplorerDataPlugin.getIconDetails("ToolstripIcon", obj.SettingsIcon);
